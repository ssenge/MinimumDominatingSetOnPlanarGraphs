# Generates lean/Op4/Table.lean from exact data (Table tab:general and the six-coin remark).
# Usage: python3 lean/scripts/gen_table.py   (needs mpmath)
import os
from fractions import Fraction as Fr
from math import floor, ceil
from mpmath import mp, mpf, log, sqrt
mp.dps = 60

def kap(q):
    return log(3) / log(1 / mpf(q.numerator) * q.denominator)

def fr(a, p):
    return (1 - p) * (1 - (1 - p) ** a) / a

ROWS = {  # a: (AS, half, best, p*, factor)
    1: ("8.23", "3.82", "3.82", Fr(1, 2), "2.15"),
    2: ("17.02", "5.30", "5.14", Fr(27, 64), "3.31"),
    3: ("25.81", "6.97", "6.42", Fr(95, 256), "4.02"),
    6: ("52.18", "12.84", "10.08", Fr(71, 256), "5.17"),
    10: ("87.34", "21.44", "14.81", Fr(55, 256), "5.89"),
    100: ("878.34", "219.18", "115.67", Fr(3, 64), "7.59"),
}
NAMES = {1: "one", 2: "two", 3: "three", 6: "six", 10: "ten", 100: "hundred"}

def dec(s):
    return Fr(s)

def rat(x):
    return f"({x.numerator} / {x.denominator} : ℝ)" if x.denominator != 1 else f"({x.numerator} : ℝ)"

out = []
w = out.append

w("""import Op4.RandomCentres

/-!
# The numbers of Table `tab:general` and the six-coin remark

Generated by `gen_table.py` from exact rational data.

For integer density `a`, Theorem `thm:level` gives the per-level fraction
`f_a(p) = (1-p)(1-(1-p)^a)/a` (`fr`), and the round exponent is `κ = ln 3/ln(1/q)` with
`q = 1 - f_a(p)`; for [1] it is `q = 1 - 1/(8a)`. For every row of the table this file checks:
* the exponent of [1], to the two printed decimals (`table_as_*`);
* our exponents for `p = 1/2` and for the best dyadic `p`, rounded up (`table_half_*`,
  `table_best_*`);
* that the printed `p` is the best among the `p = j/256`, that is, with at most `8` fair coins
  (`best_dyadic_*`);
* the improvement factor, rounded down (`table_factor_*`).
The six-coin exponent of Theorem `thm:main` is within `10⁻³` of the best exponent that
Theorem `thm:planar` gives for any `p` (`six_coins_near_best`).
-/

open Finset

namespace Op4

section Table

/-- The per-level fraction of Theorem `thm:level` for integer density `a`. -/
noncomputable def fr (a : ℕ) (p : ℝ) : ℝ := (1 - p) * (1 - (1 - p) ^ a) / a

lemma kappa_lt_nat {q : ℝ} (N D a b : ℕ) (hD : 0 < D) (hDN : D < N) (hq : q = D / N)
    (hb : 0 < b) (h : 3 ^ b * D ^ a < N ^ a) : kappa q < (a : ℝ) / b := by
  subst hq
  have hN : (0 : ℝ) < N := by exact_mod_cast hD.trans hDN
  apply kappa_lt (by positivity) (by rw [div_lt_one hN]; exact_mod_cast hDN) hb
  rw [one_div_div, div_pow, lt_div_iff₀ (by positivity)]
  exact_mod_cast h

lemma lt_kappa_nat {q : ℝ} (N D a b : ℕ) (hD : 0 < D) (hDN : D < N) (hq : q = D / N)
    (hb : 0 < b) (h : N ^ a < 3 ^ b * D ^ a) : (a : ℝ) / b < kappa q := by
  subst hq
  have hN : (0 : ℝ) < N := by exact_mod_cast hD.trans hDN
  apply lt_kappa (by positivity) (by rw [div_lt_one hN]; exact_mod_cast hDN) hb
  rw [one_div_div, div_pow, div_lt_iff₀ (by positivity)]
  exact_mod_cast h

/-- `κ` grows with `q`. -/
lemma kappa_mono {q q' : ℝ} (hq : 0 < q) (hqq : q ≤ q') (hq' : q' < 1) : kappa q ≤ kappa q' := by
  unfold kappa
  have h1 : 0 < Real.log (1 / q') := Real.log_pos (one_lt_one_div (by linarith) hq')
  have h2 : Real.log (1 / q') ≤ Real.log (1 / q) :=
    Real.log_le_log (one_div_pos.2 (by linarith)) (one_div_le_one_div_of_le hq hqq)
  exact div_le_div_of_nonneg_left (Real.log_nonneg (by norm_num)) h1 h2

/-- `f_a(j/256)` as a quotient of natural numbers. -/
lemma fr_dyadic {a : ℕ} (ha : 1 ≤ a) {j : ℕ} (hj : j ≤ 256) :
    fr a ((j : ℝ) / 256) =
      (((256 - j) * (256 ^ a - (256 - j) ^ a) : ℕ) : ℝ) / ((256 ^ (a + 1) * a : ℕ) : ℝ) := by
  unfold fr
  have h2 : (256 - j) ^ a ≤ 256 ^ a := Nat.pow_le_pow_left (Nat.sub_le _ _) a
  rw [Nat.cast_mul, Nat.cast_sub h2, Nat.cast_mul]
  push_cast [Nat.cast_sub hj]
  rw [show (1 : ℝ) - j / 256 = (256 - j) / 256 by ring, div_pow]
  have ha' : (a : ℝ) ≠ 0 := by positivity
  field_simp
  ring
""")

def kappa_two_sided(name, doc, qexpr, q, lo, hi, hqtac):
    # lo < kappa q < hi, lo = A1/B1, hi = A2/B2
    N, D = q.denominator, q.numerator
    w(f"/-- {doc} -/")
    w(f"theorem {name} : {rat(lo)} < kappa ({qexpr}) ∧ kappa ({qexpr}) < {rat(hi)} := by")
    w(f"  have hq : ({qexpr}) = (({D} : ℕ) : ℝ) / (({N} : ℕ) : ℝ) := by {hqtac}")
    w(f"  constructor")
    w(f"  · have h := lt_kappa_nat (q := {qexpr}) {N} {D} {lo.numerator} {lo.denominator} (by norm_num) (by norm_num) hq")
    w(f"      (by norm_num) (by decide +kernel)")
    w(f"    exact_mod_cast h")
    w(f"  · have h := kappa_lt_nat (q := {qexpr}) {N} {D} {hi.numerator} {hi.denominator} (by norm_num) (by norm_num) hq")
    w(f"      (by norm_num) (by decide +kernel)")
    w(f"    exact_mod_cast h")
    w("")
    # verify numerically
    k = kap(q)
    assert mpf(lo.numerator) / lo.denominator < k < mpf(hi.numerator) / hi.denominator, (name, k, lo, hi)
    assert 3 ** lo.denominator * D ** lo.numerator > N ** lo.numerator or True

def kappa_upper(name, doc, qexpr, q, hi, hqtac):
    N, D = q.denominator, q.numerator
    w(f"/-- {doc} -/")
    w(f"theorem {name} : kappa ({qexpr}) < {rat(hi)} := by")
    w(f"  have hq : ({qexpr}) = (({D} : ℕ) : ℝ) / (({N} : ℕ) : ℝ) := by {hqtac}")
    w(f"  have h := kappa_lt_nat (q := {qexpr}) {N} {D} {hi.numerator} {hi.denominator} (by norm_num) (by norm_num) hq")
    w(f"    (by norm_num) (by decide +kernel)")
    w(f"  exact_mod_cast h")
    w("")
    assert kap(q) < mpf(hi.numerator) / hi.denominator

def kappa_lower(name, doc, qexpr, q, lo, hqtac):
    N, D = q.denominator, q.numerator
    w(f"/-- {doc} -/")
    w(f"theorem {name} : {rat(lo)} < kappa ({qexpr}) := by")
    w(f"  have hq : ({qexpr}) = (({D} : ℕ) : ℝ) / (({N} : ℕ) : ℝ) := by {hqtac}")
    w(f"  have h := lt_kappa_nat (q := {qexpr}) {N} {D} {lo.numerator} {lo.denominator} (by norm_num) (by norm_num) hq")
    w(f"    (by norm_num) (by decide +kernel)")
    w(f"  exact_mod_cast h")
    w("")
    assert mpf(lo.numerator) / lo.denominator < kap(q)

for a, (AS, HALF, BEST, pstar, FAC) in ROWS.items():
    nm = NAMES[a]
    w(f"/-! ### Row `a = {a}` -/")
    w("")
    # [1]
    qas = 1 - Fr(1, 8 * a)
    x = dec(AS)
    lo, hi = x - Fr(1, 200), x + Fr(1, 200)
    kappa_two_sided(f"table_as_{nm}", f"`a = {a}`: the exponent of [1] is `{AS}` to two decimals.",
                    f"1 - 1 / (8 * {a} : ℝ)", qas, lo, hi, "norm_num")
    # p = 1/2
    qh = 1 - fr(a, Fr(1, 2))
    y = dec(HALF)
    kappa_two_sided(f"table_half_{nm}", f"`a = {a}`, `p = 1/2`: the exponent rounded up is `{HALF}`.",
                    f"1 - fr {a} (1 / 2)", qh, y - Fr(1, 100), y, "norm_num [fr]")
    # best dyadic
    qb = 1 - fr(a, pstar)
    z = dec(BEST)
    kappa_two_sided(f"table_best_{nm}",
                    f"`a = {a}`, `p = {pstar}`: the exponent rounded up is `{BEST}`.",
                    f"1 - fr {a} ({pstar.numerator} / {pstar.denominator})", qb, z - Fr(1, 100), z,
                    "norm_num [fr]")
    # optimality among j/256
    js = pstar * 256
    assert js.denominator == 1
    js = js.numerator
    gval = lambda j: (256 - j) * (256 ** a - (256 - j) ** a)
    assert all(gval(j) <= gval(js) for j in range(257))
    w(f"/-- `a = {a}`: `p = {pstar}` is the best `p = j/256`. -/")
    w(f"theorem best_dyadic_{nm} (j : ℕ) (hj : j ≤ 256) :")
    w(f"    fr {a} ((j : ℝ) / 256) ≤ fr {a} ({pstar.numerator} / {pstar.denominator}) := by")
    w(f"  have hN : ∀ j < 257, (256 - j) * (256 ^ {a} - (256 - j) ^ {a}) ≤")
    w(f"      (256 - {js}) * (256 ^ {a} - (256 - {js}) ^ {a}) := by decide +kernel")
    w(f"  rw [show ({pstar.numerator} / {pstar.denominator} : ℝ) = (({js} : ℕ) : ℝ) / 256 by norm_num,")
    w(f"    fr_dyadic (by norm_num) hj, fr_dyadic (by norm_num) (by norm_num)]")
    w(f"  exact div_le_div_of_nonneg_right (by exact_mod_cast hN j (by omega)) (by positivity)")
    w("")
    # factor
    fac = dec(FAC)
    kas, kb = kap(qas), kap(qb)
    assert kas / kb > mpf(fac.numerator) / fac.denominator
    found = None
    for B in [200, 1000, 2000, 5000, 10000, 20000, 50000, 100000]:
        L = Fr(int(mp.floor(kas * B)), B)
        U = Fr(int(mp.ceil(kb * B)), B)
        if fac * U < L:
            found = (L, U)
            break
    L, U = found
    kappa_lower(f"factor_lo_{nm}", f"`a = {a}`: a lower bound on the exponent of [1].",
                f"1 - 1 / (8 * {a} : ℝ)", qas, L, "norm_num")
    kappa_upper(f"factor_hi_{nm}", f"`a = {a}`: an upper bound on our best exponent.",
                f"1 - fr {a} ({pstar.numerator} / {pstar.denominator})", qb, U, "norm_num [fr]")
    w(f"/-- `a = {a}`: the improvement factor, rounded down, is `{FAC}`. -/")
    w(f"theorem table_factor_{nm} :")
    w(f"    {rat(fac)} < kappa (1 - 1 / (8 * {a} : ℝ)) / kappa (1 - fr {a} ({pstar.numerator} / {pstar.denominator})) := by")
    w(f"  have h1 := factor_lo_{nm}")
    w(f"  have h2 := factor_hi_{nm}")
    w(f"  have h3 := (table_best_{nm}).1")
    w(f"  rw [lt_div_iff₀ (by linarith)]")
    w(f"  linarith")
    w("")

# six coins
s = ((-8 + sqrt(64 + 84)) / 14) ** (mpf(1) / 3)
phimax = s * (3 - 2 * s ** 3 - s ** 6) / 9
M = Fr(int(phimax * 10 ** 8) + 1, 10 ** 8)
s0 = Fr(int(s * 10 ** 6), 10 ** 6)
g = [9 * M, Fr(-3), Fr(0), Fr(0), Fr(2), Fr(0), Fr(0), Fr(1)]
d = [s0 * s0, -2 * s0, Fr(1)]
qq = [Fr(0)] * 6
r = g[:]
for i in range(7, 1, -1):
    c = r[i]
    qq[i - 2] = c
    for jj in range(3):
        r[i - 2 + jj] -= c * d[jj]
assert all(c > 0 for c in qq)
h0 = qq[0]
c1 = r[1]
c0p = r[0] + r[1] * s0
assert c0p - c1 * c1 / (4 * h0) > 0
hpoly = " + ".join(f"{rat(c)} * s ^ {i}" for i, c in enumerate(qq) if i > 0)
q6 = 1 - Fr(755617505461, 4398046511104)
k6 = kap(q6)
KH = Fr(int(mp.ceil(k6 * 10 ** 4)), 10 ** 4)
qM = 1 - M
KL = Fr(int(mp.floor(kap(qM) * 10 ** 4)), 10 ** 4)
